
function escapeHtml(value = "") {
  return String(value).replace(/[&<>"']/g, (char) => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#39;"
  })[char]);
}

function jsonResponse(data, status = 200) {
  return new Response(JSON.stringify(data), {
    status,
    headers: {
      "Content-Type": "application/json"
    }
  });
}

export default async (req) => {
  // Only allow POST requests
  if (req.method !== "POST") {
    return jsonResponse(
      { error: "Method not allowed." },
      405
    );
  }

  try {
    // Parse request body
    const { name, email, rating, review, website } =
      await req.json();

    // Honeypot spam protection
    // Legitimate users should leave this field empty.
    if (
  website !== undefined &&
  website !== null &&
  String(website).trim() !== ""
) {
  return jsonResponse({ success: true });
}

    // Validate required fields
    if (
      typeof name !== "string" ||
      typeof email !== "string" ||
      typeof review !== "string" ||
      !name.trim() ||
      !email.trim() ||
      !review.trim()
    ) {
      return jsonResponse(
        { error: "Please complete all required fields." },
        400
      );
    }

    const cleanName = name.trim();
    const cleanEmail = email.trim();
    const cleanReview = review.trim();

    // Validate email
    if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(cleanEmail)) {
      return jsonResponse(
        { error: "Please enter a valid email address." },
        400
      );
    }

    // Validate input lengths
    if (
      cleanName.length > 100 ||
      cleanEmail.length > 254 ||
      cleanReview.length > 3000
    ) {
      return jsonResponse(
        { error: "One or more fields exceed the allowed length." },
        400
      );
    }

    // Validate rating
    const validRatings = ["1", "2", "3", "4", "5"];

    if (
      rating !== undefined &&
      rating !== null &&
      rating !== "" &&
      !validRatings.includes(String(rating))
    ) {
      return jsonResponse(
        { error: "Invalid rating." },
        400
      );
    }

    // Escape HTML to prevent injection
    const safeName = escapeHtml(cleanName);
    const safeEmail = escapeHtml(cleanEmail);

    const safeRating = escapeHtml(
      rating ? `${rating} / 5 Stars` : "Not provided"
    );

    const safeReview = escapeHtml(cleanReview)
      .replace(/\r\n|\r|\n/g, "<br>");

    // Email design
    const emailHTML = `
      <div style="background:#f4f6f8;padding:35px 15px;font-family:Arial,sans-serif;">
        <div style="max-width:600px;margin:auto;background:#ffffff;border-radius:12px;overflow:hidden;">

          <div style="background:#e32200;padding:28px;text-align:center;">
            <h1 style="color:#ffffff;margin:0;font-size:24px;">
              New Customer Review
            </h1>
          </div>

          <div style="padding:30px;">

            <p style="color:#555;font-size:15px;">
              A new customer has submitted a review through your website.
            </p>

            <div style="background:#f8f8f8;padding:20px;border-radius:8px;margin:20px 0;">

              <p>
                <strong>Customer:</strong> ${safeName}
              </p>

              <p>
                <strong>Email:</strong> ${safeEmail}
              </p>

              <p>
                <strong>Rating:</strong> ${safeRating}
              </p>

            </div>

            <h3 style="color:#333;">
              Customer Feedback
            </h3>

            <div style="background:#fff5f3;border-left:4px solid #e32200;padding:18px;border-radius:4px;">
              <p style="color:#444;line-height:1.7;margin:0;">
                ${safeReview}
              </p>
            </div>

            <p style="color:#999;font-size:12px;margin-top:30px;">
              This notification was automatically generated by your website.
            </p>

          </div>
        </div>
      </div>
    `;

    // Check environment variables
    const requiredEnv = [
      "MJ_APIKEY_PUBLIC",
      "MJ_APIKEY_PRIVATE",
      "MJ_SENDER_EMAIL",
      "REVIEW_RECIPIENT_EMAIL"
    ];

    for (const variable of requiredEnv) {
      if (!process.env[variable]) {
        console.error(`Missing environment variable: ${variable}`);

        return jsonResponse(
          { error: "Email service is not configured." },
          500
        );
      }
    }

    // Mailjet authentication
    const credentials = Buffer.from(
      `${process.env.MJ_APIKEY_PUBLIC}:${process.env.MJ_APIKEY_PRIVATE}`
    ).toString("base64");

    // Send email through Mailjet
    const mailjetResponse = await fetch(
      "https://api.mailjet.com/v3.1/send",
      {
        method: "POST",

        headers: {
          Authorization: `Basic ${credentials}`,
          "Content-Type": "application/json"
        },

        body: JSON.stringify({
          Messages: [
            {
              From: {
                Email: process.env.MJ_SENDER_EMAIL,
                Name: "Business Reviews"
              },

              To: [
                {
                  Email: process.env.REVIEW_RECIPIENT_EMAIL
                }
              ],

              ReplyTo: {
                Email: cleanEmail,
                Name: cleanName
              },

              Subject: `New Customer Review from ${cleanName}`,

              TextPart: `New review from ${cleanName}

Customer Email: ${cleanEmail}
Rating: ${rating || "Not provided"}

Review:
${cleanReview}`,

              HTMLPart: emailHTML
            }
          ]
        })
      }
    );

    const result = await mailjetResponse.json();

    // Check Mailjet response
    if (
      !mailjetResponse.ok ||
      result.Messages?.[0]?.Status !== "success"
    ) {
      console.error("Mailjet error:", result);

      return jsonResponse(
        { error: "Email delivery failed." },
        502
      );
    }

    // Successful submission
    return jsonResponse(
      { success: true },
      200
    );

  } catch (error) {
    console.error("Review submission error:", error);

    return jsonResponse(
      { error: "Something went wrong." },
      500
    );
  }
};
